w = out.append
for c in CHARS:
    assert len(c["head"]) == 11 and all(len(r) == 12 for r in c["head"]), c["name"]
    assert len(c["torso"]) == 6 and all(len(r) == 8 for r in c["torso"]), c["name"]
    assert set("".join(c["head"] + c["torso"])) - set(".SE") <= set(c["pal"]), c["name"]
w("static const sprite_t sprites[SPRITE_N] = {")
for c in CHARS:
    b = BLINK.get(c["name"], "S")
    w(f'    {{   // {c["name"]}')
    w("        {" + ", ".join(f'"{r}"' for r in c["head"]) + "},")
    w("        {" + ", ".join(f'"{r}"' for r in c["torso"]) + "},")
    w("        {" + ", ".join("{%d, %d, %d}" % c["pal"][k] for k in "ABCDFG") + "},")
