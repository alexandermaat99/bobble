#!/usr/bin/env python3
# Rasterises Inter (SIL Open Font License, free to ship in a product) into main/font_ui.c: anti-aliased
# 4-bit glyphs for printable ASCII at the sizes the screens use. Needs Pillow.
#   python3 tools/make_font.py path/to/Inter[opsz,wght].ttf
import sys
from PIL import ImageFont

FONTS = [  # C name, pixel size, weight
    ("font_big", 42, 600),     # the agent's speech bubble, short messages
    ("font_body", 33, 600),    # the agent's speech bubble
    ("font_label", 19, 500),   # small labels (project name)
    ("font_small", 15, 600),   # the square board's chat titles (its pixels are bigger: still easy to read)
]

def build(path, name, size, weight):
    f = ImageFont.truetype(path, size)
    try:
        vals = []
        for a in f.get_variation_axes():                 # Inter's axes: optical size, weight
            v = size if b"ptical" in bytes(a["name"]) else weight
            vals.append(max(a["minimum"], min(a["maximum"], v)))
        f.set_variation_by_axes(vals)
    except OSError:
        pass                                          # a static font: use it as is
    ascent, descent = f.getmetrics()
    glyphs, bits = [], bytearray()
    for code in range(0x20, 0x7F):
        ch = chr(code)
        mask, (ox, oy) = f.getmask2(ch, mode="L")
        w, h = mask.size
        off = len(bits)
        px = [mask.getpixel((x, y)) >> 4 for y in range(h) for x in range(w)]
        if len(px) % 2: px.append(0)
        bits += bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
        glyphs.append((off, w, h, ox, oy, round(f.getlength(ch) * 4)))
    out = [f"static const uint8_t {name}_bits[] = {{"]
    for i in range(0, len(bits), 24):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const glyph_t {name}_glyphs[] = {{")
    for g in glyphs:
        out.append("    {%d, %d, %d, %d, %d, %d}," % g)
    out.append("};")
    out.append(f"const font_t {name} = {{{name}_glyphs, {name}_bits, {ascent + descent}, {ascent}}};")
    return "\n".join(out), len(bits)

src = ["// Generated by tools/make_font.py from Inter (SIL Open Font License 1.1). Don't edit by hand.",
       '#include "gfx.h"', ""]
for name, size, weight in FONTS:
    code, n = build(sys.argv[1], name, size, weight)
    src += [f"// {name}: Inter {weight} at {size} px, {n} bytes of glyphs", code, ""]
open(__file__.rsplit("/tools/", 1)[0] + "/main/font_ui.c", "w").write("\n".join(src))
print("wrote main/font_ui.c")
