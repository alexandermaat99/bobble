#!/usr/bin/env python3
# Rasterises integration logos (Simple Icons SVGs, CC0; the brands' trademarks are their own) into
# main/icons_ui.c: a 4-bit anti-aliased mask per logo plus its brand colour (lightened where it's too dark to show on
# the black screen), drawn over the bubble while that integration is in use.
# Needs skia-python.
#   python3 tools/make_icons.py <dir with slug.svg files> <simple-icons.json>
# The directory can also hold slug.png app icons (from an app's .icns: sips -s format png): their light marks become
# the logo, in white, and the dark tile behind them (black on the display anyway) is dropped.
import json, re, sys, glob, os
import skia
from PIL import Image

SIZE = 44                                   # px

def title_to_slug(t):                       # Simple Icons' own rule, for entries without a slug
    t = t.lower().replace("+", "plus").replace(".", "dot").replace("&", "and")
    return re.sub(r"[^a-z0-9]", "", t)

data = json.load(open(sys.argv[2]))
data = data if isinstance(data, list) else data["icons"]
hexes = {d.get("slug") or title_to_slug(d["title"]): d["hex"] for d in data}

out = ["// Generated by tools/make_icons.py from Simple Icons (CC0). The logos are their owners' trademarks.",
       '#include "icons_ui.h"', ""]
table = []
def app_icon(path):
    """An app icon's light marks as a coverage mask (0..15 per pixel), cropped to them and fitted to SIZE"""
    im = Image.open(path).convert("RGBA")
    lum = Image.eval(im.convert("L"), lambda v: max(0, min(255, (v - 150) * 255 // 80)))   # (just the bright marks, not the tile's rim)
    lum = Image.composite(lum, Image.new("L", im.size, 0), im.getchannel("A"))
    box = lum.point(lambda v: 255 if v > 100 else 0).getbbox()
    lum = lum.crop(box)
    s = SIZE / max(lum.size)
    lum = lum.resize((max(1, round(lum.width * s)), max(1, round(lum.height * s))), Image.LANCZOS)
    canvas = Image.new("L", (SIZE, SIZE), 0)
    canvas.paste(lum, ((SIZE - lum.width) // 2, (SIZE - lum.height) // 2))
    return [v >> 4 for v in canvas.getdata()]

for path in sorted(glob.glob(os.path.join(sys.argv[1], "*.svg")) + glob.glob(os.path.join(sys.argv[1], "*.png"))):
    slug = os.path.basename(path)[:-4]
    if path.endswith(".png"):
        a = app_icon(path)
        packed = bytes((a[i] << 4) | a[i + 1] for i in range(0, len(a), 2))
        name = "icon_" + slug
        out.append(f"static const uint8_t {name}[] = {{" + ", ".join(f"0x{v:02x}" for v in packed) + "};")
        table.append(f'    {{"{slug}", {name}, 255, 255, 255}},')
        continue
    dom = skia.SVGDOM.MakeFromStream(skia.Stream.MakeFromFile(path))
    if dom is None:
        continue
    dom.setContainerSize(skia.Size(SIZE, SIZE))     # (the 24x24 viewBox, scaled to fit)
    surface = skia.Surface(SIZE, SIZE)
    canvas = surface.getCanvas()
    canvas.clear(skia.ColorTRANSPARENT)
    dom.render(canvas)
    px = surface.makeImageSnapshot().toarray()     # RGBA rows
    a = [px[y][x][3] >> 4 for y in range(SIZE) for x in range(SIZE)]
    packed = bytes((a[i] << 4) | a[i + 1] for i in range(0, len(a), 2))
    h = hexes.get(slug, "202028")
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    lum = 0.2126 * r + 0.7152 * g + 0.0722 * b     # too dark for black (GitHub, Notion, Slack's aubergine): lighten
    if lum < 90:                                    # towards white until it reads; near-black becomes white
        t = 1 if max(r, g, b) - min(r, g, b) < 40 else (110 - lum) / (255 - lum)
        t = min(1, t)
        r, g, b = (round(c + (255 - c) * t) for c in (r, g, b))
    name = "icon_" + slug
    out.append(f"static const uint8_t {name}[] = {{" + ", ".join(f"0x{v:02x}" for v in packed) + "};")
    table.append(f'    {{"{slug}", {name}, {r}, {g}, {b}}},')
out += ["", "const icon_t icons_ui[] = {"] + table + ["    {0, 0, 0, 0, 0},", "};", ""]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "main", "icons_ui.c"), "w").write("\n".join(out))
print(f"wrote main/icons_ui.c ({len(table)} icons)")
