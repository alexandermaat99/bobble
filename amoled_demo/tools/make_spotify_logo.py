#!/usr/bin/env python3
# Rasterises Spotify's logo (the Simple Icons SVG, CC0; the logo is Spotify's trademark) into main/spotify_logo.h:
# a 4-bit anti-aliased coverage mask (two pixels a byte, high nibble first) for the square's Spotify page, which
# draws it in Spotify green (the sound waves are holes in the disc, so they come out black).
# Needs skia-python.
#   curl -sLO https://cdn.jsdelivr.net/npm/simple-icons@latest/icons/spotify.svg
#   python3 tools/make_spotify_logo.py spotify.svg
import os, sys
import skia

SIZE = 104                                  # px (the page's LOGO_R * 2)

dom = skia.SVGDOM.MakeFromStream(skia.Stream.MakeFromFile(sys.argv[1]))
dom.setContainerSize(skia.Size(SIZE, SIZE))  # (the 24x24 viewBox, scaled to fit)
surface = skia.Surface(SIZE, SIZE)
canvas = surface.getCanvas()
canvas.clear(skia.ColorTRANSPARENT)
dom.render(canvas)
px = surface.makeImageSnapshot().toarray()   # RGBA rows
a = [(int(px[y][x][3]) + 8) * 15 // 255 for y in range(SIZE) for x in range(SIZE)]
packed = bytes((a[i] << 4) | a[i + 1] for i in range(0, len(a), 2))

out = ["// Generated by tools/make_spotify_logo.py from Simple Icons (CC0). The logo is Spotify's trademark.",
       "#pragma once", "#include <stdint.h>", "",
       f"#define SPOTIFY_LOGO_SIZE {SIZE}", "static const uint8_t spotify_logo[] = {"]
for i in range(0, len(packed), SIZE // 2):
    out.append("    " + ", ".join(f"0x{v:02x}" for v in packed[i:i + SIZE // 2]) + ",")
out += ["};", ""]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "main", "spotify_logo.h"), "w").write("\n".join(out))
print(f"wrote main/spotify_logo.h ({SIZE}x{SIZE})")
